-- Oracle 12c ou superior. Modelo extraído de docs/easifybddoc.pdf, páginas 3-5.
-- Executar uma vez no schema do usuário conectado. Não remove tabelas existentes.
-- Identity implementa os IDs automáticos; o PDF não fornece sequences/DDL.
CREATE TABLE ANALISE (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    UUID_ANALISE VARCHAR2(36 BYTE) NOT NULL,
    CLIENTE_NOME VARCHAR2(500 BYTE) NOT NULL,
    CLIENTE_EMPRESA VARCHAR2(500 BYTE) NOT NULL,
    VENDEDOR_NOME VARCHAR2(500 BYTE) NOT NULL,
    PRODUTO_RECOMENDADO CLOB NOT NULL,
    NIVEL_INTERESSE VARCHAR2(20 BYTE) NOT NULL,
    RISCO_CHURN VARCHAR2(20 BYTE) NOT NULL,
    PROXIMA_ACAO CLOB NOT NULL,
    RESUMO CLOB NOT NULL,
    DATA_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_ANALISE PRIMARY KEY (ID),
    CONSTRAINT UQ_ANALISE_UUID UNIQUE (UUID_ANALISE),
    CONSTRAINT CK_ANALISE_INTERESSE CHECK (NIVEL_INTERESSE IN ('BAIXO', 'MEDIO', 'ALTO', 'NAO_IDENTIFICADO')),
    CONSTRAINT CK_ANALISE_RISCO CHECK (RISCO_CHURN IN ('BAIXO', 'MEDIO', 'ALTO', 'NAO_IDENTIFICADO'))
);

CREATE TABLE ANALISE_DOR (
    ANALISE_ID NUMBER NOT NULL,
    POSICAO NUMBER NOT NULL,
    DESCRICAO CLOB NOT NULL,
    CONSTRAINT PK_ANALISE_DOR PRIMARY KEY (ANALISE_ID, POSICAO),
    CONSTRAINT FK_ANALISE_DOR FOREIGN KEY (ANALISE_ID) REFERENCES ANALISE(ID) ON DELETE CASCADE
);

CREATE TABLE ANALISE_CONCORRENTE (
    ANALISE_ID NUMBER NOT NULL,
    POSICAO NUMBER NOT NULL,
    DESCRICAO CLOB NOT NULL,
    CONSTRAINT PK_ANALISE_CONC PRIMARY KEY (ANALISE_ID, POSICAO),
    CONSTRAINT FK_ANALISE_CONC FOREIGN KEY (ANALISE_ID) REFERENCES ANALISE(ID) ON DELETE CASCADE
);

CREATE TABLE TRANSCRICAO (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ANALISE_ID NUMBER NOT NULL,
    TEXTO_ORIGINAL CLOB NOT NULL,
    DATA_REGISTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_TRANSCRICAO PRIMARY KEY (ID),
    CONSTRAINT UQ_TRANSCRICAO_ANALISE UNIQUE (ANALISE_ID),
    CONSTRAINT FK_TRANSCRICAO_ANALISE FOREIGN KEY (ANALISE_ID) REFERENCES ANALISE(ID) ON DELETE CASCADE
);

CREATE TABLE STATUS_ACOMPANHAMENTO (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ANALISE_ID NUMBER NOT NULL,
    STATUS VARCHAR2(20 BYTE) NOT NULL,
    OBSERVACAO VARCHAR2(1000 BYTE),
    DATA_MUDANCA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_STATUS_ACOMP PRIMARY KEY (ID),
    CONSTRAINT FK_STATUS_ACOMP_ANALISE FOREIGN KEY (ANALISE_ID) REFERENCES ANALISE(ID) ON DELETE CASCADE,
    CONSTRAINT CK_STATUS_ACOMP CHECK (STATUS IN ('PENDENTE', 'EM_ANDAMENTO', 'CONCLUIDO', 'DESCARTADO'))
);