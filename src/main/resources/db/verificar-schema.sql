-- Consultas somente de leitura para comparar o banco existente com easifybddoc.pdf.
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_LENGTH, CHAR_USED, NULLABLE, DATA_DEFAULT
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME IN ('ANALISE', 'ANALISE_DOR', 'ANALISE_CONCORRENTE', 'TRANSCRICAO', 'STATUS_ACOMPANHAMENTO')
ORDER BY TABLE_NAME, COLUMN_ID;

SELECT TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE, R_CONSTRAINT_NAME, DELETE_RULE,
       STATUS, SEARCH_CONDITION
FROM USER_CONSTRAINTS
WHERE TABLE_NAME IN ('ANALISE', 'ANALISE_DOR', 'ANALISE_CONCORRENTE', 'TRANSCRICAO', 'STATUS_ACOMPANHAMENTO')
ORDER BY TABLE_NAME, CONSTRAINT_NAME;

SELECT TABLE_NAME, CONSTRAINT_NAME, COLUMN_NAME, POSITION
FROM USER_CONS_COLUMNS
WHERE TABLE_NAME IN ('ANALISE', 'ANALISE_DOR', 'ANALISE_CONCORRENTE', 'TRANSCRICAO', 'STATUS_ACOMPANHAMENTO')
ORDER BY TABLE_NAME, CONSTRAINT_NAME, POSITION;

SELECT TABLE_NAME, COLUMN_NAME, GENERATION_TYPE, SEQUENCE_NAME
FROM USER_TAB_IDENTITY_COLS
WHERE TABLE_NAME IN ('ANALISE', 'TRANSCRICAO', 'STATUS_ACOMPANHAMENTO');