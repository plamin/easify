package com.totvs.easifyai.infrastructure.persistence;

import java.nio.charset.StandardCharsets;
import java.nio.file.Path;
import java.util.UUID;

/** Banco isolado para testes. Executa o mesmo DDL, com adaptação exclusiva da sintaxe identity. */
public final class BancoTeste {
    private BancoTeste() { }

    public static ConexaoBanco criar(Path arquivo) {
        var banco = new ConexaoBanco("jdbc:h2:file:" + arquivo.toAbsolutePath() + ";MODE=Oracle",
                "sa", UUID.randomUUID().toString());
        inicializar(banco);
        return banco;
    }

    public static void inicializar(ConexaoBanco banco) {
        try (var recurso = BancoTeste.class.getResourceAsStream("/db/schema.sql")) {
            if (recurso == null) {
                throw new IllegalStateException("DDL não encontrado.");
            }
            String ddl = new String(recurso.readAllBytes(), StandardCharsets.UTF_8)
                    .replaceAll("(?m)^\\s*--[^\\r\\n]*", "")
                    .replace("NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY",
                            "BIGINT GENERATED BY DEFAULT AS IDENTITY");
            try (var conexao = banco.abrir(); var statement = conexao.createStatement()) {
                for (String comando : ddl.split(";")) {
                    if (!comando.isBlank()) {
                        statement.execute(comando);
                    }
                }
            }
        } catch (Exception e) {
            throw new IllegalStateException("Falha ao preparar banco de teste.", e);
        }
    }
}